const selector = document.querySelector("#language");
const initial = (navigator.language || "en").slice(0, 2);
const current = messages[initial] ? initial : "en";

function applyLanguage(language) {
  const table = messages[language] || messages.en;
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    if (table[key]) node.textContent = table[key];
  });
}

selector.value = current;
applyLanguage(current);
selector.addEventListener("change", (event) => applyLanguage(event.target.value));
